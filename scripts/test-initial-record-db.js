// Synthetic PostgreSQL regression. No .env, ports, mounts, or application DB.
// Requires the already-local postgres:17-bookworm image; never pulls an image.
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const { spawnSync } = require('node:child_process');

const root = path.resolve(__dirname, '..');
function load(relative, dependencies) {
  const module = { exports: {} };
  vm.runInNewContext(fs.readFileSync(path.join(root, relative), 'utf8'), {
    module, exports: module.exports, __dirname: path.dirname(path.join(root, relative)),
    require(name) {
      if (Object.hasOwn(dependencies, name)) return dependencies[name];
      throw new Error(`Unexpected dependency in isolated SQL capture: ${name}`);
    },
    process: { env: {} }, console: { log() {} },
  }, { filename: relative });
  return module.exports;
}
const literal = value => value == null ? 'NULL' : typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const bind = (sql, values) => sql.replace(/\$(\d+)/g, (_, index) => literal(values[Number(index) - 1]));

